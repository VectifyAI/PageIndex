"""Two-tier, checkpointed summaries over a PageIndex tree.

tier="summary": short routing text (JSON reply, `summary` field), leaves
under `small_node_tokens` reuse raw text. tier="digest": longer Markdown,
always generated by the model. Both are bottom-up: parents see their
children's same-tier text. Nodes already carrying the field are skipped
unless force=True, which is what makes an interrupted run resumable when
the caller persists after every node via on_node."""
from __future__ import annotations

import asyncio
import json
import logging
from typing import Callable, Iterable

from .. import utils
from . import prompts
from .pages import page_text

logger = logging.getLogger(__name__)

TIERS = ("summary", "digest")
SMALL_NODE_TOKENS = 200
INTRO_MAX_PAGES = 3
DEFAULT_CONCURRENCY = 3


def _expand_to_subtrees(structure: list[dict], node_ids: set[str]) -> set[str]:
    """`node_ids` selects whole subtrees, not single nodes: "digest chapter 12"
    means every node under chapter 12, not the chapter node alone with hollow
    children. Returns the union of each selected node's id and every one of
    its descendants' ids, so visit()'s bottom-up gather generates every
    child's tier text before a selected parent's parent_text() reads it."""
    by_id = {n.get("node_id"): n for n in utils.structure_to_list(structure)}
    expanded: set[str] = set()
    for node_id in node_ids:
        node = by_id.get(node_id)
        if node is None:
            continue
        expanded.update(n.get("node_id") for n in utils.structure_to_list(node))
    return expanded


def _intro_text(node: dict, page_texts: list[str], max_pages: int) -> str:
    children = node.get("nodes") or []
    first_child = children[0].get("start_index") if children else None
    if not isinstance(first_child, int) or first_child <= node["start_index"]:
        return ""
    end = min(first_child - 1, node["start_index"] + max_pages - 1)
    return page_text(page_texts, node["start_index"], end)


async def summarize_tier(structure: list[dict], page_texts: list[str], *, tier: str,
                         profile: str, model: str, book: str,
                         on_node: Callable[[dict], None] | None = None,
                         force: bool = False, node_ids: Iterable[str] | None = None,
                         small_node_tokens: int = SMALL_NODE_TOKENS,
                         max_intro_pages: int = INTRO_MAX_PAGES,
                         concurrency: int | None = None) -> dict:
    if tier not in TIERS:
        raise ValueError(f"tier must be one of {TIERS}, got {tier!r}")
    wanted = _expand_to_subtrees(structure, set(node_ids)) if node_ids is not None else None
    model_field = f"{tier}_model"
    semaphore = asyncio.Semaphore(concurrency or DEFAULT_CONCURRENCY)
    stats = {"generated": 0, "skipped": 0, "failed": 0, "errors": []}

    def selected(node: dict) -> bool:
        return wanted is None or node.get("node_id") in wanted

    async def ask(prompt: str) -> str:
        async with semaphore:
            return await utils.llm_acompletion(model, prompt)

    async def leaf_text(node: dict) -> tuple[str, str]:
        text = page_text(page_texts, node["start_index"], node["end_index"])
        if tier == "summary" and utils.count_tokens(text, model="gpt-4o") < small_node_tokens:
            return text.strip(), "raw"
        prompt = prompts.render(profile, tier, "leaf", book=book,
                                title=node.get("title", ""), text=text)
        reply = await ask(prompt)
        return (utils.parse_summary(reply) if tier == "summary" else reply.strip()), model

    async def parent_text(node: dict) -> tuple[str, str]:
        listing = json.dumps([{"title": c.get("title", ""), tier: c.get(tier, "")}
                              for c in node["nodes"]], ensure_ascii=False)
        prompt = prompts.render(profile, tier, "parent", book=book,
                                title=node.get("title", ""),
                                intro=_intro_text(node, page_texts, max_intro_pages),
                                children=listing)
        reply = await ask(prompt)
        return (utils.parse_summary(reply) if tier == "summary" else reply.strip()), model

    async def visit(node: dict) -> None:
        children = node.get("nodes") or []
        if children:
            await asyncio.gather(*(visit(child) for child in children))
        if not selected(node):
            return
        if node.get(tier) and not force:
            stats["skipped"] += 1
            return
        try:
            text, used = await (parent_text(node) if children else leaf_text(node))
        except Exception as exc:  # noqa: BLE001 - per-node failure is data
            if utils._is_unrecoverable(exc):
                raise
            stats["failed"] += 1
            stats["errors"].append(f"{node.get('node_id')} {node.get('title', '')!r}: {exc}")
            logger.warning("summary failed for %s: %s", node.get("node_id"), exc)
            return
        if not text:
            stats["failed"] += 1
            stats["errors"].append(f"{node.get('node_id')}: empty reply")
            return
        node[tier] = text
        node[model_field] = used
        stats["generated"] += 1
        if on_node is not None:
            on_node(node)

    await asyncio.gather(*(visit(root) for root in structure))
    return stats


def _pages_as_texts(pages: list[dict]) -> list[str]:
    return [p.get("markdown", "") for p in pages]


def summarize_book(store, doc_id: str, *, tier: str, model: str, force: bool = False,
                   node_ids: Iterable[str] | None = None, concurrency: int | None = None,
                   small_node_tokens: int = SMALL_NODE_TOKENS) -> dict:
    meta = store.get_meta(doc_id)
    if meta is None:
        raise KeyError(f"Unknown doc_id: {doc_id!r}")
    tree = store.get_tree(doc_id) or []
    page_texts = _pages_as_texts(store.get_pages(doc_id) or [])
    extra = meta.get("metadata") or {}
    profile = extra.get("profile", "nonfiction")
    book = extra.get("title") or meta.get("name", "")

    def checkpoint(_node: dict) -> None:
        store.save_tree(doc_id, tree)

    stats = utils.run_off_loop(asyncio.run, summarize_tier(
        tree, page_texts, tier=tier, profile=profile, model=model, book=book,
        on_node=checkpoint, force=force, node_ids=node_ids,
        small_node_tokens=small_node_tokens, concurrency=concurrency))
    store.save_tree(doc_id, tree)
    complete = all(n.get(tier) for n in utils.structure_to_list(tree)) if node_ids is None else \
        bool(extra.get(f"{tier}_tier_done"))
    store.update_meta(doc_id, metadata={**extra, f"{tier}_tier_done": complete})
    return stats


def describe_book(store, doc_id: str, *, model: str) -> str:
    meta = store.get_meta(doc_id)
    if meta is None:
        raise KeyError(f"Unknown doc_id: {doc_id!r}")
    tree = store.get_tree(doc_id) or []
    extra = meta.get("metadata") or {}
    profile = extra.get("profile", "nonfiction")
    book = extra.get("title") or meta.get("name", "")
    outline = json.dumps(utils.create_clean_structure_for_description(tree), ensure_ascii=False)
    prompt = prompts.render(profile, "description", "doc", book=book, structure=outline)
    text = (utils.llm_completion(model, prompt) or "").strip()
    store.update_meta(doc_id, description=text)
    return text
